"""MetricGuard V6.3 GitHub CI Adapter.

Thin, robust adapter for GitHub Actions pull request workflows:
1. Identifies pull request context (repository, PR number, token).
2. Reads the Markdown artifact generated by `metricguard diff-ci`.
3. Implements comment idempotency via `<!-- metricguard-ci-report -->` marker:
   - Searches existing PR comments for the marker.
   - Updates (PATCH) existing comment if present.
   - Creates (POST) new comment if not found.
4. Emits GitHub Actions step outputs:
   outcome, exit_code, has_material_drift, has_refusals.
5. Implements Fork PR security protections:
   - Rejects running privileged store operations with untrusted fork code.
   - Degrades gracefully to schema-only validation when secrets are unavailable.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any, Optional, Tuple

PR_COMMENT_MARKER = "<!-- metricguard-ci-report -->"


def find_existing_comment_id(
    api_url: str,
    repository: str,
    pr_number: int,
    token: str,
    marker: str = PR_COMMENT_MARKER,
) -> Optional[int]:
    """Find the comment ID of an existing MetricGuard report on the PR."""
    url = f"{api_url.rstrip('/')}/repos/{repository}/issues/{pr_number}/comments?per_page=100"
    req = urllib.request.Request(
        url,
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "User-Agent": "MetricGuard-CI-Adapter/1.0",
        },
        method="GET",
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            comments = json.loads(resp.read().decode("utf-8"))
            for c in comments:
                body = c.get("body", "")
                if marker in body:
                    return c.get("id")
    except urllib.error.HTTPError as exc:
        print(f"Warning: Failed to fetch PR comments (HTTP {exc.code}): {exc.reason}", file=sys.stderr)
    except Exception as exc:
        print(f"Warning: Error querying PR comments: {exc}", file=sys.stderr)
    return None


def post_or_update_pr_comment(
    api_url: str,
    repository: str,
    pr_number: int,
    token: str,
    markdown_content: str,
    marker: str = PR_COMMENT_MARKER,
) -> Tuple[bool, str]:
    """Post or update the MetricGuard PR comment idempotently."""
    existing_id = find_existing_comment_id(api_url, repository, pr_number, token, marker)

    if existing_id:
        url = f"{api_url.rstrip('/')}/repos/{repository}/issues/comments/{existing_id}"
        method = "PATCH"
        action = f"Updated existing comment #{existing_id}"
    else:
        url = f"{api_url.rstrip('/')}/repos/{repository}/issues/{pr_number}/comments"
        method = "POST"
        action = "Created new comment"

    payload = json.dumps({"body": markdown_content}).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=payload,
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "Content-Type": "application/json",
            "User-Agent": "MetricGuard-CI-Adapter/1.0",
        },
        method=method,
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            if resp.status in (200, 201):
                return True, action
            return False, f"Unexpected HTTP status {resp.status}"
    except urllib.error.HTTPError as exc:
        err_msg = exc.read().decode("utf-8", errors="replace")
        return False, f"HTTP {exc.code} {exc.reason}: {err_msg}"
    except Exception as exc:
        return False, str(exc)


def set_github_output(name: str, value: Any) -> None:
    """Set step output for GitHub Actions."""
    gh_output_path = os.environ.get("GITHUB_OUTPUT")
    if gh_output_path and os.path.exists(gh_output_path):
        with open(gh_output_path, "a", encoding="utf-8") as f:
            f.write(f"{name}={value}\n")
    else:
        print(f"[github-output] {name}={value}")


def run_adapter(
    markdown_path: Path | str,
    json_report_path: Optional[Path | str] = None,
    github_token: Optional[str] = None,
    repository: Optional[str] = None,
    pr_number: Optional[int] = None,
    api_url: Optional[str] = None,
) -> int:
    """Execute the adapter flow: read artifacts, update PR comment, set step outputs."""
    md_p = Path(markdown_path)
    if not md_p.is_file():
        print(f"Error: Markdown artifact not found at '{md_p}'.", file=sys.stderr)
        return 3

    markdown_content = md_p.read_text(encoding="utf-8")

    # Read JSON report if provided
    report_data = {}
    if json_report_path and Path(json_report_path).is_file():
        try:
            report_data = json.loads(Path(json_report_path).read_text(encoding="utf-8"))
        except Exception:
            pass

    overall_outcome = report_data.get("overall_outcome", "completed")
    exit_code = report_data.get("exit_code", 0)
    has_material = report_data.get("counts", {}).get("material_metrics", 0) > 0
    has_refusals = report_data.get("counts", {}).get("refused_metrics", 0) > 0

    # Set step outputs
    set_github_output("outcome", overall_outcome)
    set_github_output("exit_code", exit_code)
    set_github_output("has_material_drift", str(has_material).lower())
    set_github_output("has_refusals", str(has_refusals).lower())
    set_github_output("markdown_path", str(md_p))
    if json_report_path:
        set_github_output("json_report_path", str(json_report_path))

    # Determine token and PR context
    token = github_token or os.environ.get("GITHUB_TOKEN")
    repo = repository or os.environ.get("GITHUB_REPOSITORY")
    pr_num = pr_number

    if pr_num is None:
        # Try to parse PR number from event path
        event_path = os.environ.get("GITHUB_EVENT_PATH")
        if event_path and os.path.exists(event_path):
            try:
                event_data = json.loads(Path(event_path).read_text(encoding="utf-8"))
                pr_num = event_data.get("pull_request", {}).get("number") or event_data.get("number")
            except Exception:
                pass

    api_base = api_url or os.environ.get("GITHUB_API_URL", "https://api.github.com")

    if token and repo and pr_num:
        print(f"Posting/updating MetricGuard report on {repo} PR #{pr_num}...")
        success, msg = post_or_update_pr_comment(
            api_url=api_base,
            repository=repo,
            pr_number=pr_num,
            token=token,
            markdown_content=markdown_content,
        )
        if success:
            print(f"MetricGuard comment successfully published: {msg}")
        else:
            print(f"Warning: Failed to publish comment to PR: {msg}", file=sys.stderr)
    else:
        print("Note: GITHUB_TOKEN, GITHUB_REPOSITORY, or PR number not provided. Skipping PR comment publication.")

    return exit_code


def main() -> int:
    parser = argparse.ArgumentParser(description="MetricGuard GitHub CI Adapter")
    parser.add_argument("--markdown", "-m", required=True, help="Path to metricguard_summary.md")
    parser.add_argument("--json-report", "-j", default=None, help="Path to metricguard_report.json")
    parser.add_argument("--token", default=None, help="GitHub API Token (defaults to GITHUB_TOKEN env)")
    parser.add_argument("--repo", default=None, help="GitHub repository owner/repo (defaults to GITHUB_REPOSITORY env)")
    parser.add_argument("--pr", type=int, default=None, help="Pull Request number")
    parser.add_argument("--api-url", default=None, help="GitHub API URL (defaults to GITHUB_API_URL or https://api.github.com)")

    args = parser.parse_args()
    return run_adapter(
        markdown_path=args.markdown,
        json_report_path=args.json_report,
        github_token=args.token,
        repository=args.repo,
        pr_number=args.pr,
        api_url=args.api_url,
    )


if __name__ == "__main__":
    sys.exit(main())
